from ..i18n import DEFAULT_LANG, translate

register = template.Library()


@register.simple_tag(takes_context=True)
def t(context, key):
    """{% t "key" %} → translated string in the current UI language."""
    request = context.get("request")
    lang = getattr(request, "ui_lang", None) or context.get("LANG") or DEFAULT_LANG
    return translate(key, lang)


@register.filter
def lang_label(code, ui_lang="ar"):
    return translate(f"lang_{code or 'unknown'}", ui_lang)


@register.filter
def pct(value, digits=0):
    try:
        return f"{float(value):.{int(digits)}f}%"
    except (TypeError, ValueError):
        return "—"


@register.filter
def num(value, digits=0):
    """Locale-independent number formatting: 12,345.6"""
    try:
        return f"{float(value):,.{int(digits)}f}"
    except (TypeError, ValueError):
        return "—"


@register.filter
def confpct(value):
    """0.9412 → '94.1%'"""
    try:
        return f"{float(value) * 100:.1f}%"
    except (TypeError, ValueError):
        return "—"


@register.filter
def get_item(d, key):
    try:
        return d.get(key)
    except AttributeError:
        return None


